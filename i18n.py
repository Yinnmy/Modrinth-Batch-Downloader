def set_language(code):
    """Define o idioma ativo (ignora códigos desconhecidos)."""
    global _current
    if code in STRINGS:
        _current = code


def get_language():
    return _current


def tr(key, **params):
    """Traduz uma chave; ``params`` são aplicados com str.format."""
    text = STRINGS.get(_current, {}).get(key) or STRINGS["en"].get(key) or STRINGS["pt"].get(key) or key
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError, ValueError):
            return text
    return text


